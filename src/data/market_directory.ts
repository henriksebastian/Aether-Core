/**
 * Fast lookup map by uppercase symbol
 */
const INSTRUMENT_MAP = new Map<string, MarketInstrument>();
for (const inst of MARKET_INSTRUMENTS) {
  INSTRUMENT_MAP.set(inst.symbol.toUpperCase(), inst);
}

/**
 * Returns contract specifications and metadata for any symbol.
 * If not found, generates a standardized dynamic fallback specification without crashing.
 */
export function getInstrument(symbol: string): MarketInstrument {
  const clean = symbol.toUpperCase().replace('/', '');
  const found = INSTRUMENT_MAP.get(clean);
  if (found) return found;

  // Fallback for custom or unlisted tickers
  return {
    symbol: clean,
    name: `${clean} Instrument`,
    assetClass: clean.endsWith('USDT') ? 'CRYPTO' : 'EQUITY',
    exchange: clean.endsWith('USDT') ? 'BINANCE' : 'NASDAQ',
    exchangeFullName: clean.endsWith('USDT') ? 'Binance Global' : 'NASDAQ Stock Market',
    region: 'GLOBAL',
    currency: clean.endsWith('USDT') ? 'USDT' : 'USD',
    currencySymbol: '$',
    baseAsset: clean.replace('USDT', ''),
    quoteAsset: clean.endsWith('USDT') ? 'USDT' : 'USD',
    tickSize: 0.01,
    decimals: 2,
    lotSize: 1,
    referencePrice: 100.0,
    volatility: 0.30,
    sector: 'Global Financial Markets',
    marketCap: '$10.0B',
    isCrypto: clean.endsWith('USDT'),
  };
}

/**
 * Formats a price value with the appropriate currency symbol and precision for the instrument.
 */
export function formatInstrumentPrice(price: number, instrument: MarketInstrument): string {
  if (isNaN(price) || price === null || price === undefined) return '...';
  return `${instrument.currencySymbol}${price.toLocaleString('en-US', {
    minimumFractionDigits: instrument.decimals,
    maximumFractionDigits: instrument.decimals,
  })}`;
}
